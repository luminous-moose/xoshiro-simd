(* fill_insecure_bigarray over many whole blocks: one stray byte first
   (fill_insecure_bytes always consumes a whole 32-byte block, even for a
   single byte), then 140 int64 elements = 1120 bytes = 35 whole blocks and no
   tail. The dumps above never reach the bulk loop (every length there is
   under one block), so this is what pins it -- on big-endian hosts int64 goes
   straight through xs256simd_fill_bytes with no byte swapping. The dump itself
   is too long to review element by element, so this is pinned as a digest of
   the printed (host-independent, since it hashes the native-value hex text
   rather than raw memory) dump string instead -- still a real regression guard,
   and still directly comparable against s390x/powerpc hosts like the
   tests above. *)
let print_bigarray_block_crossing_dump seed =
  let state = Xs_S.init_deterministic ~backend:Xs.Plain seed in
  Xs_S.fill_insecure_bytes state (Bytes.create 1) 1;
  (* Never wraps (break = n), so the digested string doesn't depend on
     [prefix]: it isn't printed directly, only hashed. *)
  let dump = dump_int64 ~break:140 ~prefix:"" state ~n:140 in
  printf "seed = %Lu\n" seed;
  printf "int64 (140 elements) after 1 stray byte, digest: %s\n"
    (Stdlib.Digest.to_hex (Stdlib.Digest.string dump))

