(* Mixed operations on one state: scalar draws, byte fills, bigarray fills
   and float fills interleaved. Every other vector above exercises one
   operation family per fresh state, so none of them would notice the
   families disagreeing about who owns what: byte fills and float bulk fills
   advance the shared lane state directly, while scalar draws go through the
   int and float caches (int_idx/float_idx), and a fill that leaves a cache
   stale, or a scalar draw that fails to see a fill's state advance, only
   shows up in a sequence like this. The sequence deliberately puts scalar
   draws on both sides of every kind of fill, and includes fills that end
   mid-block (5, 40 and 11 int32 bytes) so the rounding-up rule is on the
   critical path too.

   Only operations whose results are host-independent are used (no [full_int]
   or [nativebits], whose width follows the host word size). Floats are printed
   as their raw IEEE bit patterns, not as decimal text. Like the vectors above,
   the pinned output must pass unchanged on any s390x, powerpc, arm64, armhf and
   i386 hosts; on top of that, every available backend must reproduce Plain's log
   exactly. *)
let hex_of_bytes b = Hex.show (Hex.of_bytes b)

let mixed_operation_log ~backend seed =
  let state = Xs_S.init_deterministic ~backend seed in
  let log = Buffer.create 1024 in
  let add fmt =
    Printf.ksprintf (fun s -> Buffer.add_string log (s ^ "\n")) fmt
  in
  let add_float name f = add "%s: %016Lx" name (Int64.bits_of_float f) in
  add "bits64: %016Lx" (Xs_S.bits64 state);
  add "bits64: %016Lx" (Xs_S.bits64 state);
  add_float "uniform_float" (Xs_S.uniform_float state);
  add "get_insecure_bytes 5: %s"
    (hex_of_bytes (Xs_S.get_insecure_bytes state 5));
  add "int 1000: %d" (Xs_S.int state 1000);
  add "int 1000: %d" (Xs_S.int state 1000);
  add "int 1000000: %d" (Xs_S.int state 1_000_000);
  let f64 = Bigarray.Array1.create Bigarray.float64 Bigarray.c_layout 7 in
  Xs_S.fill_float64_bigarray state f64;
  add "fill_float64_bigarray 7: %s"
    (String.concat ~sep:" "
       (List.init 7 ~f:(fun i ->
            Printf.sprintf "%016Lx"
              (Int64.bits_of_float (Bigarray.Array1.get f64 i)))));
  add_float "uniform_float" (Xs_S.uniform_float state);
  let buf = Bytes.make 48 '\000' in
  Xs_S.fill_insecure_bytes state buf 40;
  add "fill_insecure_bytes 40: %s (tail untouched: %b)"
    (hex_of_bytes (Bytes.sub buf ~pos:0 ~len:40))
    (Bytes.equal (Bytes.sub buf ~pos:40 ~len:8) (Bytes.make 8 '\000'));
  add "bits32: %08lx" (Xs_S.bits32 state);
  add "bool: %b" (Xs_S.bool state);
  add "bool: %b" (Xs_S.bool state);
  let f32 = Bigarray.Array1.create Bigarray.float32 Bigarray.c_layout 9 in
  Xs_S.fill_float32_bigarray state f32;
  add "fill_float32_bigarray 9: %s"
    (String.concat ~sep:" "
       (List.init 9 ~f:(fun i ->
            Printf.sprintf "%08lx"
              (Int32.bits_of_float (Bigarray.Array1.get f32 i)))));
  add "int64 1000000000000: %Ld" (Xs_S.int64 state 1_000_000_000_000L);
  add "int32 in_range: %ld" (Xs_S.int32_in_range state ~min:(-500l) ~max:500l);
  add "fill_insecure_bigarray int32 11: %s"
    (dump_int32 ~break:11 ~prefix:"fill_insecure_bigarray int32 11: " state
       ~n:11);
  add_float "uniform_float" (Xs_S.uniform_float state);
  let f64r = Bigarray.Array1.create Bigarray.float64 Bigarray.c_layout 5 in
  Xs_S.fill_float64_range_bigarray state f64r ~min:(-2.0) ~max:6.0;
  add "fill_float64_range_bigarray 5: %s"
    (String.concat ~sep:" "
       (List.init 5 ~f:(fun i ->
            Printf.sprintf "%016Lx"
              (Int64.bits_of_float (Bigarray.Array1.get f64r i)))));
  add "get_insecure_bytes 33: %s"
    (hex_of_bytes (Xs_S.get_insecure_bytes state 33));
  add "bits64: %016Lx" (Xs_S.bits64 state);
  add_float "uniform_float" (Xs_S.uniform_float state);
  add "bits32: %08lx" (Xs_S.bits32 state);
  Buffer.contents log

let%test_unit
    "mixed operations are bit-identical across every available backend" =
  List.iter vector_files ~f:(fun filename ->
      let v = load_vector filename in
      let baseline = mixed_operation_log ~backend:Xs.Plain v.seed in
      List.iter (Xs.available_backends ()) ~f:(fun backend ->
          assert (String.equal baseline (mixed_operation_log ~backend v.seed))))

