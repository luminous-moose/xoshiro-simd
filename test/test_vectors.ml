(* fill_insecure_bigarray edge cases: n=0, odd element counts (so the byte
   length is not a multiple of the 8-byte word, unlike the power-of-2 counts
   above), and every fill after the first starting from a state the previous
   fill already advanced. Each call generates whole 32-byte blocks straight
   into the destination and discards the rest of its last block (see
   xs256simd_fill_bytes), so fill k reads the first bytes of block k-1: these
   dumps only ever reach the partial-block tail path. Pinned from a
   little-endian host, comparable directly against s390x/powerpc hosts. *)
let print_bigarray_edge_case_dump seed =
  let loop_over_element_sizes title dump_fn ~n =
    let state = Xs_S.init_deterministic ~backend:Xs.Plain seed in
    for i = 0 to n do
      let prefix = Printf.sprintf "%s (%d elements): " title i in
      printf "%s%s\n" prefix (dump_fn ~prefix state ~n:i)
    done
  in
  printf "seed = %Lu\n" seed;
  loop_over_element_sizes "int8_unsigned" (dump_int8_unsigned ~break:8) ~n:8;
  loop_over_element_sizes "int16_unsigned" (dump_int16_unsigned ~break:8) ~n:8;
  loop_over_element_sizes "int32" (dump_int32 ~break:6) ~n:6;
  loop_over_element_sizes "int64" (dump_int64 ~break:3) ~n:3

