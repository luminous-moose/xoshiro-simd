(* fill_insecure_bytes/fill_insecure_bigarray byte-order
   independence: xs256simd_fill_bytes* (xs256_common.c) canonicalize each
   word's raw bytes on big-endian hosts, so these two -- like bits64/split
   -- must produce identical bytes on every host for a fixed seed. On every
   little-endian host (this one included) that canonicalization is a no-op, so
   this %expect block already matches here; the point of pinning it is that the
   identical block must also pass unchanged on s390x/powerpc hosts -- if it
   doesn't, the fix has a bug. Plain backend, like the vectors above, so the dump
   is stable regardless of a build machine's available SIMD features. *)
let bytes_of_ba ba =
  let n = Bigarray.Array1.dim ba in
  let b = Bytes.create n in
  for i = 0 to n - 1 do
    Bytes.set b i (Char.of_int_exn (Bigarray.Array1.get ba i))
  done;
  b

let print_insecure_fill_dump seed =
  let len = 24 in
  let state_bytes = Xs_S.init_deterministic ~backend:Xs.Plain seed in
  let buf = Bytes.create len in
  Xs_S.fill_insecure_bytes state_bytes buf len;
  let state_ba = Xs_S.init_deterministic ~backend:Xs.Plain seed in
  let ba =
    Bigarray.Array1.create Bigarray.int8_unsigned Bigarray.c_layout len
  in
  Xs_S.fill_insecure_bigarray state_ba ba;
  assert (Bytes.equal buf (bytes_of_ba ba));
  printf "seed = %Lu\n" seed;
  printf "fill_insecure_bytes/fill_insecure_bigarray %d bytes:\n  %s\n" len
    (Hex.show (Hex.of_bytes buf))

