(* nativebits, nativeint and nativeint_in_range draw 32 or 64 bits depending on
   the host word size, so they can't go in the shared log above. Each width
   gets its own pinned output instead: the same draws, tagged so that each
   test only runs on hosts of its width. The 32-bit output was generated on
   i386 and must also pass on armhf and powerpc; the 64-bit output must also
   pass on arm64 and s390x. Bounds are written so they compile on both widths. *)
let native_log seed =
  let state = Xs_S.init_deterministic seed in
  for _ = 1 to 4 do
    printf "nativebits: %nd\n" (Xs_S.nativebits state)
  done;
  printf "nativeint 1000000: %nd\n" (Xs_S.nativeint state 1_000_000n);
  printf "nativeint max_int: %nd\n" (Xs_S.nativeint state Nativeint.max_value);
  printf "nativeint_in_range -1000..1000: %nd\n"
    (Xs_S.nativeint_in_range state ~min:(-1000n) ~max:1000n);
  printf "nativeint_in_range min..max: %nd\n"
    (Xs_S.nativeint_in_range state ~min:Nativeint.min_value
       ~max:Nativeint.max_value);
  printf "nativeint_in_range min..-1: %nd\n"
    (Xs_S.nativeint_in_range state ~min:Nativeint.min_value ~max:(-1n));
  printf "next bits32: %08lx\n" (Xs_S.bits32 state)

