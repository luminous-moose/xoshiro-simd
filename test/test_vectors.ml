(* Ground-truth vectors in ../testvectors/ were generated by seeding the
   unmodified upstream xoshiro256++ reference (vendored verbatim from
   https://prng.di.unimi.it/xoshiro256plusplus.c) via splitmix64 from a plain
   integer seed, then dumping the first 20 raw next() outputs. See
   ../testvectors/README.md for full provenance.

   [Xs_S.init_deterministic] seeds lane 0 directly via the identical
   splitmix64 construction (see setup() in xs256_common.c); lanes 1-3 are
   derived from it via jump and so diverge from the single-stream
   reference immediately. The bitstream interleaves all 4 lanes'
   outputs round-robin (bitstream.(i * 4 + lane), see xs256_block_plain in
   xs256_core_plain_c.c), so only every 4th word starting at index 0 is lane
   0's raw next() stream, which is what's comparable to the reference vectors.

   The vector files also document each seed's initial s[0..3] right after
   splitmix64 seeding, but that isn't checked here: init_deterministic eagerly
   computes a full 128-word block up front (see
   xs256simdintf_internal_create_from_seed in xs256_stubs.c), so by the time
   for_testing_raw_dump can observe it, lane 0's state has already advanced 32
   next() calls (one per round of the 128-word/4-lane block) past the seeded
   value the file recorded. Only the output words survive that advance
   unchanged, so they're the only thing compared. *)

let outputs_checked = 20

type vector = { seed : int64; outputs : int64 array }

let parse_vector_file path =
  let seed = ref None in
  let outputs = ref [] in
  In_channel.with_file path ~f:(fun ic ->
      In_channel.iter_lines ic ~f:(fun line ->
          let line = String.strip line in
          match String.chop_prefix line ~prefix:"# splitmix64 seed = " with
          | Some rest -> seed := Some (Int64.of_string rest)
          | None ->
              if String.is_prefix line ~prefix:"0x" then
                outputs := Int64.of_string line :: !outputs));
  {
    seed =
      Option.value_exn !seed ~message:(path ^ ": missing splitmix64 seed line");
    outputs = Array.of_list (List.rev !outputs);
  }

let vectors_dir = "../testvectors"

let vector_files =
  [ "vectors_seed0.txt"; "vectors_seed1.txt"; "vectors_seed42.txt" ]

let load_vector filename =
  parse_vector_file (Stdlib.Filename.concat vectors_dir filename)

(* Lane 0's raw output stream. bitstream is dword (int32)-granular, and each
   generator qword occupies two adjacent dwords, low half then high half
   (xs256_block_plain's little-endian layout, see xs256_common.h). The four
   lanes interleave round-robin at qword granularity (bitstream.(i * 4 + lane)
   in qword units), so lane 0's i-th qword sits at dword indices i*8 (low)
   and i*8+1 (high); bit_and with 0xffffffffL zero-extends each dword before
   combining, since Int64.of_int32 sign-extends. *)
let lane0_stream bitstream ~len =
  Array.init len ~f:(fun i ->
      let lo = Int64.bit_and (Int64.of_int32 bitstream.(i * 8)) 0xffffffffL in
      let hi =
        Int64.bit_and (Int64.of_int32 bitstream.((i * 8) + 1)) 0xffffffffL
      in
      Int64.(bit_or lo (shift_left hi 32)))

(* Checks [v] against a from-scratch state using [backend], without printing
   anything: used to sweep every backend available on the build machine, whose
   membership varies by host and so can't be pinned in an %expect block. *)
let check_vector ~backend v =
  let state = Xs_S.init_deterministic ~backend v.seed in
  ignore @@ Xs_S.bits state;
  let { Xs_S.bitstream; _ } = Xs_S.for_testing_raw_dump state in
  let actual_outputs = lane0_stream bitstream ~len:(Array.length v.outputs) in
  assert (Array.equal Int64.equal actual_outputs v.outputs)

let%test_unit "reference vectors match on every available backend" =
  List.iter vector_files ~f:(fun filename ->
      let v = load_vector filename in
      assert (Array.length v.outputs = outputs_checked);
      List.iter (Xs.available_backends ()) ~f:(fun backend ->
          check_vector ~backend v))

(* Unlike the int bitstream above, there's no external ground-truth vector
   file for xoshiro256+'s float path -- the vendored reference only covers
   xoshiro256++. What's checked here instead is the property this project's
   whole SIMD dispatch strategy exists to guarantee: every backend must
   produce bit-identical output from the same seed, regardless of native
   vector width (the logical interleave width is fixed at 4 streams, so
   narrower backends just issue more vector ops to cover the same 4
   lanes). Plain is the trusted baseline: it's always available and has no
   SIMD-specific bit tricks (the shift/OR-into-mantissa/subtract sequence
   each SIMD backend also implements) to get wrong. *)
let check_float_vector_consistency seed =
  let dump backend =
    let state = Xs_S.init_deterministic ~backend seed in
    ignore @@ Xs_S.uniform_float state;
    let { Xs_S.floatstream; _ } = Xs_S.for_testing_raw_dump state in
    (* floatstream is a floatarray (Stdlib.Float.Array.t), which has no
       built-in equal -- map_to_array converts it to a plain float array so
       the existing Base Array.equal comparison below still works unchanged. *)
    Stdlib.Float.Array.map_to_array Fn.id floatstream
  in
  let baseline = dump Xs.Plain in
  List.iter (Xs.available_backends ()) ~f:(fun backend ->
      assert (Array.equal Float.equal baseline (dump backend)))

let%test_unit "floatstream is bit-identical across every available backend" =
  List.iter vector_files ~f:(fun filename ->
      let v = load_vector filename in
      check_float_vector_consistency v.seed)

(* Human-readable dump against a fixed backend (Plain, present on every host) so
   the %expect block below is stable across build machines regardless of
   which SIMD features are available. *)
let print_vector_dump filename =
  let v = load_vector filename in
  let state = Xs_S.init_deterministic ~backend:Xs.Plain v.seed in
  ignore @@ Xs_S.bits state;
  let { Xs_S.bitstream; _ } = Xs_S.for_testing_raw_dump state in
  let actual_outputs = lane0_stream bitstream ~len:(Array.length v.outputs) in
  assert (Array.equal Int64.equal actual_outputs v.outputs);
  printf "seed = %Lu\n" v.seed;
  printf "first %d outputs:\n" (Array.length actual_outputs);
  Array.iter actual_outputs ~f:(fun w -> printf "  0x%016Lx\n" w)

