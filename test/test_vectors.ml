(* Bulk and tail together, for each element width: 100 bytes = 3 whole blocks
   plus a 4-byte tail for the 1-, 2- and 4-byte kinds, and 13 int64 elements
   = 104 bytes = 3 whole blocks plus an 8-byte tail. On big-endian hosts each
   of these goes through a different per-word transform in
   fill_bytes_be_transformed (bswap64 for int8, chunk reversal for
   int16, half swap for int32, none for int64), so a wrong destination offset
   or transform in the bulk loop or in the tail-after-bulk copy shows up here
   and nowhere else. Pinned from a little-endian host. *)
let print_bigarray_bulk_and_tail_dump seed =
  let fresh () = Xs_S.init_deterministic ~backend:Xs.Plain seed in
  printf "seed = %Lu\n" seed;
  let prefix8 = "int8_unsigned (100 elements): " in
  printf "%s%s\n" prefix8 (dump_int8_unsigned (fresh ()) ~n:100 ~prefix:prefix8);
  let prefix16 = "int16_unsigned (50 elements): " in
  printf "%s%s\n" prefix16
    (dump_int16_unsigned (fresh ()) ~n:50 ~prefix:prefix16);
  let prefix32 = "int32 (25 elements): " in
  printf "%s%s\n" prefix32 (dump_int32 (fresh ()) ~n:25 ~prefix:prefix32);
  let prefix64 = "int64 (13 elements): " in
  printf "%s%s\n" prefix64 (dump_int64 (fresh ()) ~n:13 ~prefix:prefix64)

