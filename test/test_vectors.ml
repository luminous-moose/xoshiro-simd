(* fill_insecure_bigarray element-kind dump: on a big-endian host,
   xs256simdintf_get_bytes_ba (xs256_stubs.c) dispatches per Bigarray element
   kind so that a native read (Bigarray.Array1.get, which always uses the
   host's native byte order for multi-byte kinds) recovers the same *value*
   as on a little-endian host, for int8/int16/int32/int64 alike -- not just
   matching raw bytes like the test above. Each dump below re-seeds fresh
   (so idx=0 and the fill starts qword-aligned) and fills the same byte
   count sliced into a different element kind, so this %expect block --
   pinned here from a little-endian host -- can be run unchanged on s390x and
   powerpc big-endian hosts as a regression test of that guarantee: any element
   width whose printed values differ from what's pinned here would mean a
   real, host-dependent difference in what a caller sees when treating the
   filled memory as that typed integer. Plain backend, like the vectors above,
   for build-machine stability. *)
(* [prefix] is the exact text that will precede the dump on the printed line
   (e.g. "int8_unsigned (32 elements): "), used only to compute how many
   spaces a wrapped continuation line needs to line up under the first hex
   byte -- it is never printed by this function itself. Deriving the indent
   from the real prefix, rather than a hand-counted literal, means it can't
   drift out of alignment when the same function is reused at a call site
   whose prefix has a different length (e.g. a different number of digits in
   the element count). The indent is one column shorter than [prefix] itself:
   [String.concat ~sep:" "] below inserts its own separator space right after
   our embedded "\n" ^ indent, so a full-length indent would overshoot by one.

   [i <> n - 1] excludes the last element from the wrap check: without it, an
   [n] that's an exact multiple of [break] would also wrap after the final
   byte, leaving a dangling "newline + indent" with nothing after it. *)
let dump_int8_unsigned ?(break = 16) ~prefix state ~n =
  let indent = String.make (max 0 (String.length prefix - 1)) ' ' in
  let ba = Bigarray.Array1.create Bigarray.int8_unsigned Bigarray.c_layout n in
  Xs_S.fill_insecure_bigarray state ba;
  String.concat ~sep:" "
    (List.init n ~f:(fun i ->
         let newline =
           if i <> n - 1 && i % break = break - 1 then "\n" ^ indent else ""
         in
         Printf.sprintf "%02x%s" (Bigarray.Array1.get ba i) newline))

