let () = Printexc.record_backtrace true
let () = Random.self_init ()
let available () = true

(* ~20% of bounds are > 2^30, exercising full_int's 64-bit-only large-bound
   path; the rest are small enough for int on any platform. On 32-bit
   builds every bound is small, since large ones don't fit in a 32-bit native
   int. Bounds are fixed literals from bench_data.ml, not generated by calling
   full_int/int themselves, so this stays comparable across code changes to
   those functions. *)
let tests, name =
  let ranges = Bench_data.full_int_bounds in
  let idx = ref 0 in
  let nextrange () =
    if !idx = 64 then idx := 0;
    let v = ranges.(!idx) in
    idx := !idx + 1;
    v
  in
  let dls : Bench_common.test list =
    [
      {
        name = "stdlib-dls";
        available;
        test =
          (fun () ->
            ignore (Sys.opaque_identity (Random.full_int (nextrange ()))));
      };
      {
        name = Bench_backend.dls_name ();
        available;
        test =
          (fun () ->
            ignore (Sys.opaque_identity (Xoshiro_simd.full_int (nextrange ()))));
      };
    ]
  in
  let c_state =
    Xoshiro_simd.State.init_deterministic ~backend:Plain Bench_data.seed64
  in
  let stdlib_state = Random.get_state () in
  (* No gsl entry: gsl_rng_uniform_int raises if the bound exceeds
     the generator's own range (gsl_rng_max, 2^32-1 for the
     default generator), which ~20% of these bounds do. *)
  (* Splittable_random < v0.17 (needed for 32-bit, where newer
     versions are unavailable) only has [of_int] nested under
     [State]; newer versions hoist it to the top level and
     deprecate the [State] alias. *)
  let splittable_state =
    (Splittable_random.State.of_int [@alert "-deprecated"]) 42
  in
  let pringo_state = PRNG.Splitmix.State.make [| 1; 2; 3; 4 |] in
  let xoshiro_state = Xoshiro.State.make [| 1; 2; 3; 4 |] in
  (* The states below are set with a try/with expression so that they are plain
     values, not optionals or lazy, because slower access to those could ruin
     the benchmark results. *)
  let sse2_state =
    try Xoshiro_simd.State.init ~backend:Sse2 ()
    with Invalid_argument _ -> c_state
  in
  let avx2_state =
    try Xoshiro_simd.State.init ~backend:Avx2 ()
    with Invalid_argument _ -> c_state
  in
  let avx512fvl_state =
    try Xoshiro_simd.State.init ~backend:Avx512fvl ()
    with Invalid_argument _ -> c_state
  in
  let neon_state =
    try Xoshiro_simd.State.init ~backend:Neon ()
    with Invalid_argument _ -> c_state
  in
  let backend_tests : Bench_common.test list =
    [
      {
        name = "stdlib";
        available;
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Random.State.full_int stdlib_state (nextrange ()))));
      };
      {
        name = "splittable_random";
        available;
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Splittable_random.int splittable_state ~lo:0
                    ~hi:(nextrange () - 1))));
      };
      {
        name = "pringo";
        available;
        test =
          (fun () ->
            (* pringo's plain [int] is capped at 2^30 - 1, same restriction
               stdlib's plain [Random.int] has (which is exactly why full_int
               exists), so this goes through [int64] instead, for every bound.
               See pringo-dispatch below for the variant that uses [int] where
               it can. *)
            ignore
              (Sys.opaque_identity
                 (Int64.to_int
                    (PRNG.Splitmix.State.int64 pringo_state
                       (Int64.of_int (nextrange ()))))));
      };
      {
        name = "xoshiro";
        available;
        test =
          (fun () ->
            (* Same reasoning as pringo above: xoshiro's plain [int] is capped
               at 2^30 - 1. *)
            ignore
              (Sys.opaque_identity
                 (Int64.to_int
                    (Xoshiro.State.int64 xoshiro_state
                       (Int64.of_int (nextrange ()))))));
      };
      {
        name = "pringo-dispatch";
        available;
        test =
          (fun () ->
            (* What a user who knows the cap would write: the cheaper native
               [int] for bounds it accepts, [int64] only above it. Shows pringo
               at its best for a mixed-bound workload; the plain "pringo" entry
               above shows the cost of one call that handles any bound without
               that branch. *)
            let n = nextrange () in
            ignore
              (Sys.opaque_identity
                 (if n <= 0x3FFFFFFF then PRNG.Splitmix.State.int pringo_state n
                  else
                    Int64.to_int
                      (PRNG.Splitmix.State.int64 pringo_state (Int64.of_int n)))));
      };
      {
        name = "xoshiro-dispatch";
        available;
        test =
          (fun () ->
            (* Same as pringo-dispatch above. *)
            let n = nextrange () in
            ignore
              (Sys.opaque_identity
                 (if n <= 0x3FFFFFFF then Xoshiro.State.int xoshiro_state n
                  else
                    Int64.to_int
                      (Xoshiro.State.int64 xoshiro_state (Int64.of_int n)))));
      };
      {
        name = "xoshiro-simd-plain";
        available;
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Xoshiro_simd.State.full_int c_state (nextrange ()))));
      };
      {
        name = "xoshiro-simd-sse2";
        available = (fun () -> Bench_backend.supported Sse2);
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Xoshiro_simd.State.full_int sse2_state (nextrange ()))));
      };
      {
        name = "xoshiro-simd-avx2";
        available = (fun () -> Bench_backend.supported Avx2);
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Xoshiro_simd.State.full_int avx2_state (nextrange ()))));
      };
      {
        name = "xoshiro-simd-avx512fvl";
        available = (fun () -> Bench_backend.supported Avx512fvl);
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Xoshiro_simd.State.full_int avx512fvl_state (nextrange ()))));
      };
      {
        name = "xoshiro-simd-neon";
        available = (fun () -> Bench_backend.supported Neon);
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Xoshiro_simd.State.full_int neon_state (nextrange ()))));
      };
    ]
  in
  (dls @ backend_tests, "full_int")

let () = Bench_common.run_and_print name tests
