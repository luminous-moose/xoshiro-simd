(* Fixed benchmark inputs, shared by every benchmark executable so that
   different implementations and libraries are always compared on identical
   data. The values were generated once, randomly, with Stdlib.Random and
   pinned here as literals, so they don't depend on the compiler version, as
   Random's algorithm changed in OCaml 5.

   Pinning matters beyond reproducibility: the cost of the range functions
   depends on the bounds (idiv latency on some CPUs, rejection branches), so
   bounds that differed between runs, or were drawn from the generator under
   test, would make before/after comparisons depend on the draw, not the
   code. *)

(* Cycles through a fixed array of bounds/values (e.g. one of the arrays
   below), wrapping around at the end. The compare-and-reset (rather than
   [mod]) is deliberate: this runs inside the timed loop, and an idiv there
   would be measured too. *)
let make_cycler arr =
  let n = Array.length arr in
  let idx = ref 0 in
  fun () ->
    if !idx = n then idx := 0;
    let v = arr.(!idx) in
    incr idx;
    v

