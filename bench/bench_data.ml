(* Every 5th bound is drawn from the large pool, the rest from the small
   one, so roughly 20% of draws exercise the large-bound path of the function
   under test. *)
let is_large i = i mod 5 = 0

(* Large bounds are > 2^30, exercising full_int's 64-bit-only large-bound
   path. On 32-bit builds every bound is small: large ones don't fit in a
   native int at all, even as a literal, which is why the pool is int64 and
   only converted inside the 64-bit branch. *)
let full_int_bounds =
  Array.init (Array.length full_int_small) (fun i ->
      if Sys.word_size = 64 && is_large i then Int64.to_int full_int_large.(i)
      else full_int_small.(i))

(* Large bounds are >= 2^32, exercising intrange_int64's large-bound path. *)
let int64_bounds =
  Array.init (Array.length int64_small) (fun i ->
      if is_large i then int64_large.(i) else int64_small.(i))
