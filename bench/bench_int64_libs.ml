(* ~20% of bounds are >= 2^32, exercising intrange_int64's large-bound path;
   the rest are small, but still int64s. Bounds are fixed literals from
   bench_data.ml, not generated by calling int64 itself, so this stays
   comparable across code changes to that function. *)
let () = Printexc.record_backtrace true
let () = Random.self_init ()
let available () = true

let tests, name =
  let auto_state = Xoshiro_simd.State.init ~backend:Auto () in
  let ranges = Bench_data.int64_bounds in
  let nextrange = Bench_data.make_cycler ranges in
  let stdlib_state = Random.get_state () in
  (* No gsl entry: gsl has no int64 API at all (Gsl.Rng.uniform_int takes
     a plain int bound), and even restricted to what fits in a native int
     it's still capped by gsl_rng_max (2^32-1 for the default generator),
     well under what these bounds need. *)
  (* Splittable_random < v0.17 (needed for 32-bit, where newer versions are
     unavailable) only has [of_int] nested under [State]; newer versions hoist
     it to the top level and deprecate the [State] alias. *)
  let splittable_state =
    (Splittable_random.State.of_int [@alert "-deprecated"]) 42
  in
  let pringo_state = PRNG.Splitmix.State.make [| 1; 2; 3; 4 |] in
  let xoshiro_state = Xoshiro.State.make [| 1; 2; 3; 4 |] in
  let dls : Bench_common.test list =
    [
      {
        name = "stdlib-dls";
        available;
        test =
          (fun () -> ignore (Sys.opaque_identity (Random.int64 (nextrange ()))));
      };
      {
        name = Bench_backend.dls_name ();
        available;
        test =
          (fun () ->
            ignore (Sys.opaque_identity (Xoshiro_simd.int64 (nextrange ()))));
      };
    ]
  in
  let common : Bench_common.test list =
    [
      {
        name = "stdlib";
        available;
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Random.State.int64 stdlib_state (nextrange ()))));
      };
      {
        name = "splittable_random";
        available;
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Splittable_random.int64 splittable_state ~lo:0L
                    ~hi:(Int64.sub (nextrange ()) 1L))));
      };
      {
        name = "pringo";
        available;
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (PRNG.Splitmix.State.int64 pringo_state (nextrange ()))));
      };
      {
        name = "xoshiro";
        available;
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Xoshiro.State.int64 xoshiro_state (nextrange ()))));
      };
      {
        name = Bench_backend.auto_name auto_state;
        available;
        test =
          (fun () ->
            ignore
              (Sys.opaque_identity
                 (Xoshiro_simd.State.int64 auto_state (nextrange ()))));
      };
    ]
  in
  (dls @ common, "int64-libs")

let () = Bench_common.run_and_print name tests
